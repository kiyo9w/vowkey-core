import { execFile, spawn } from "child_process";
import { existsSync, mkdirSync, readFileSync } from "fs";
import * as fs from "fs/promises";
import * as os from "os";
import * as path from "path";
import { promisify } from "util";

import { DesktopIpcPeerClientType } from "@vowkey/common/platform/ipc";

import type { NativeMessagingMain } from "../../main/native-messaging.main";
import type { FocusedInputField } from "../types";

const run = promisify(execFile);

const BRIDGE_VERSION = "v1";

/**
 * Self-contained macOS Accessibility + Concealed Pasteboard helper:
 * 1. `inspect`: Enables `AXManualAccessibility` + `AXEnhancedUserInterface` on the frontmost app,
 *    reads `AXWebArea` (`AXURL` / `AXDocument`) without AppleScript Automation prompts, and
 *    returns screen bounds + labels (`AXTitle`, `AXDescription`, `AXPlaceholderValue`, `AXSubrole`)
 *    for any focused `<input>` / text control.
 * 2. `paste`: Reads JSON segments over `stdin` (never `argv`), snapshots `NSPasteboard.general`,
 *    writes each text segment with `org.nspasteboard.ConcealedType`, `TransientType`, and
 *    `AutoGeneratedType`, posts `⌘V` / `Tab`, and restores the previous pasteboard snapshot 150 ms
 *    later if `changeCount` matches.
 */
const MACOS_AX_BRIDGE_SWIFT = `
import AppKit
import ApplicationServices
import Foundation

struct FocusedFieldOut: Codable {
  let role: String
  let subrole: String?
  let title: String?
  let description: String?
  let placeholder: String?
  let isSecure: Bool
  let x: Double
  let y: Double
  let width: Double
  let height: Double
}

struct InspectOut: Codable {
  let appName: String?
  let bundleId: String?
  let pid: Int32
  let windowTitle: String?
  let webUrl: String?
  let docUrl: String?
  let focusedField: FocusedFieldOut?
}

struct PasteSegmentIn: Codable {
  let kind: String
  let value: String?
}

struct PasteRequestIn: Codable {
  let segments: [PasteSegmentIn]
  let totp: String?
}

func axString(_ elem: AXUIElement, _ attr: String) -> String? {
  var ref: CFTypeRef?
  let status = AXUIElementCopyAttributeValue(elem, attr as CFString, &ref)
  guard status == .success, let val = ref else { return nil }
  if CFGetTypeID(val) == CFStringGetTypeID() {
    let s = (val as! String).trimmingCharacters(in: .whitespacesAndNewlines)
    return s.isEmpty ? nil : s
  }
  if CFGetTypeID(val) == CFURLGetTypeID() {
    let u = val as! URL
    let s = u.absoluteString.trimmingCharacters(in: .whitespacesAndNewlines)
    return s.isEmpty ? nil : s
  }
  return nil
}

func axElement(_ elem: AXUIElement, _ attr: String) -> AXUIElement? {
  var ref: CFTypeRef?
  guard AXUIElementCopyAttributeValue(elem, attr as CFString, &ref) == .success,
        let val = ref,
        CFGetTypeID(val) == AXUIElementGetTypeID() else { return nil }
  return (val as! AXUIElement)
}

func axChildren(_ elem: AXUIElement) -> [AXUIElement] {
  var ref: CFTypeRef?
  guard AXUIElementCopyAttributeValue(elem, kAXChildrenAttribute as CFString, &ref) == .success,
        let arr = ref as? [AXUIElement] else { return [] }
  return arr
}

func isUsableUrl(_ s: String?) -> Bool {
  guard let s = s else { return false }
  return s.hasPrefix("https://") || s.hasPrefix("http://") || s.hasPrefix("file://")
}

func findWebUrlFromAncestors(_ start: AXUIElement) -> String? {
  var cur: AXUIElement? = start
  var depth = 0
  while let node = cur, depth < 36 {
    if let u = axString(node, "AXURL"), isUsableUrl(u) { return u }
    if let d = axString(node, kAXDocumentAttribute as String), isUsableUrl(d) { return d }
    cur = axElement(node, kAXParentAttribute as String)
    depth += 1
  }
  return nil
}

func findWebUrlInWindow(_ win: AXUIElement) -> String? {
  if let u = axString(win, "AXURL"), isUsableUrl(u) { return u }
  var queue: [AXUIElement] = [win]
  var idx = 0
  while idx < queue.count && idx < 96 {
    let node = queue[idx]
    idx += 1
    if axString(node, kAXRoleAttribute as String) == "AXWebArea" {
      if let u = axString(node, "AXURL"), isUsableUrl(u) { return u }
      if let d = axString(node, kAXDocumentAttribute as String), isUsableUrl(d) { return d }
    }
    let kids = axChildren(node)
    if !kids.isEmpty {
      queue.append(contentsOf: kids.prefix(24))
    }
  }
  return nil
}

func runInspect() {
  guard let front = NSWorkspace.shared.frontmostApplication else {
    print("{}")
    return
  }
  let pid = front.processIdentifier
  let appElem = AXUIElementCreateApplication(pid)
  _ = AXUIElementSetAttributeValue(appElem, "AXManualAccessibility" as CFString, kCFBooleanTrue)
  _ = AXUIElementSetAttributeValue(appElem, "AXEnhancedUserInterface" as CFString, kCFBooleanTrue)

  let win = axElement(appElem, kAXFocusedWindowAttribute as String)
    ?? axElement(appElem, kAXMainWindowAttribute as String)
  let winTitle = win.flatMap { axString($0, kAXTitleAttribute as String) }
  let docUrl = win.flatMap { axString($0, kAXDocumentAttribute as String) }

  var webUrl: String? = nil
  var focusedOut: FocusedFieldOut? = nil

  if let focused = axElement(appElem, kAXFocusedUIElementAttribute as String) {
    webUrl = findWebUrlFromAncestors(focused)
    let role = axString(focused, kAXRoleAttribute as String) ?? ""
    if ["AXTextField", "AXTextArea", "AXComboBox", "AXSearchField"].contains(role) {
      var posRef: CFTypeRef?
      var sizeRef: CFTypeRef?
      var pt = CGPoint.zero
      var sz = CGSize.zero
      let hasPos = AXUIElementCopyAttributeValue(focused, kAXPositionAttribute as CFString, &posRef) == .success
        && posRef != nil && AXValueGetValue(posRef as! AXValue, .cgPoint, &pt)
      let hasSize = AXUIElementCopyAttributeValue(focused, kAXSizeAttribute as CFString, &sizeRef) == .success
        && sizeRef != nil && AXValueGetValue(sizeRef as! AXValue, .cgSize, &sz)
      if hasPos && hasSize && sz.width > 0 && sz.height > 0 {
        let subrole = axString(focused, kAXSubroleAttribute as String)
        focusedOut = FocusedFieldOut(
          role: role,
          subrole: subrole,
          title: axString(focused, kAXTitleAttribute as String),
          description: axString(focused, kAXDescriptionAttribute as String),
          placeholder: axString(focused, kAXPlaceholderValueAttribute as String),
          isSecure: subrole == "AXSecureTextField",
          x: Double(pt.x),
          y: Double(pt.y),
          width: Double(sz.width),
          height: Double(sz.height)
        )
      }
    }
  }

  if webUrl == nil, let w = win {
    webUrl = findWebUrlInWindow(w)
  }

  let out = InspectOut(
    appName: front.localizedName,
    bundleId: front.bundleIdentifier,
    pid: pid,
    windowTitle: winTitle,
    webUrl: (webUrl?.hasPrefix("http") == true) ? webUrl : nil,
    docUrl: docUrl ?? ((webUrl?.hasPrefix("file://") == true) ? webUrl : nil),
    focusedField: focusedOut
  )
  if let data = try? JSONEncoder().encode(out), let json = String(data: data, encoding: .utf8) {
    print(json)
  } else {
    print("{}")
  }
}

func postKey(_ src: CGEventSource?, keyCode: CGKeyCode, flags: CGEventFlags) {
  for down in [true, false] {
    guard let ev = CGEvent(keyboardEventSource: src, virtualKey: keyCode, keyDown: down) else { continue }
    ev.flags = flags
    ev.post(tap: .cghidEventTap)
  }
}

func runPaste() {
  let stdinData = FileHandle.standardInput.readDataToEndOfFile()
  guard let req = try? JSONDecoder().decode(PasteRequestIn.self, from: stdinData) else {
    exit(1)
  }

  let pb = NSPasteboard.general
  let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
  let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
  let autoGen = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

  var snapshot: [[(NSPasteboard.PasteboardType, Data)]] = []
  for item in pb.pasteboardItems ?? [] {
    if item.types.contains(concealed) || item.types.contains(transient) {
      continue
    }
    var pairs: [(NSPasteboard.PasteboardType, Data)] = []
    for t in item.types {
      if let d = item.data(forType: t) {
        pairs.append((t, d))
      }
    }
    if !pairs.isEmpty {
      snapshot.append(pairs)
    }
  }

  let src = CGEventSource(stateID: .hidSystemState)
  var lastChangeCount: Int? = nil

  for seg in req.segments {
    if seg.kind == "tab" {
      Thread.sleep(forTimeInterval: 0.02)
      postKey(src, keyCode: 0x30, flags: [])
      Thread.sleep(forTimeInterval: 0.045)
    } else if seg.kind == "return" {
      Thread.sleep(forTimeInterval: 0.02)
      postKey(src, keyCode: 0x24, flags: [])
      Thread.sleep(forTimeInterval: 0.04)
    } else if let text = seg.value, !text.isEmpty {
      pb.clearContents()
      pb.setString(text, forType: .string)
      pb.setData(Data(), forType: concealed)
      pb.setData(Data(), forType: transient)
      pb.setData(Data(), forType: autoGen)
      lastChangeCount = pb.changeCount
      postKey(src, keyCode: 0x09, flags: .maskCommand)
      Thread.sleep(forTimeInterval: 0.055)
    }
  }

  if let totp = req.totp, !totp.isEmpty {
    Thread.sleep(forTimeInterval: 0.08)
    pb.clearContents()
    pb.setString(totp, forType: .string)
    pb.setData(Data(), forType: concealed)
    pb.setData(Data(), forType: autoGen)
    return
  }

  if let expected = lastChangeCount {
    Thread.sleep(forTimeInterval: 0.15)
    if pb.changeCount == expected {
      pb.clearContents()
      if !snapshot.isEmpty {
        let restored: [NSPasteboardItem] = snapshot.map { pairs in
          let it = NSPasteboardItem()
          for (t, d) in pairs {
            it.setData(d, forType: t)
          }
          return it
        }
        pb.writeObjects(restored)
      }
    }
  }
}

let mode = CommandLine.arguments.dropFirst().first ?? "inspect"
if mode == "paste" {
  runPaste()
} else {
  runInspect()
}
`;

export interface AxInspectResult {
  appName?: string;
  bundleId?: string;
  pid?: number;
  windowTitle?: string;
  webUrl?: string;
  docUrl?: string;
  focusedField?: FocusedInputField;
}

export type ConcealedSegment =
  | { kind: "text"; value: string }
  | { kind: "tab" }
  | { kind: "return" };

export class MacosAxBridge {
  private binaryPath: string | null = null;
  private buildPromise: Promise<string | null> | null = null;
  private extensionCache = new Map<string, { active: boolean; expiresAt: number }>();

  constructor(private userDataPath: string) {}

  async ensureBinary(): Promise<string | null> {
    if (process.platform !== "darwin") {
      return null;
    }
    if (this.binaryPath && existsSync(this.binaryPath)) {
      return this.binaryPath;
    }
    if (this.buildPromise) {
      return this.buildPromise;
    }
    this.buildPromise = this.compileIfNeeded();
    return this.buildPromise;
  }

  private async compileIfNeeded(): Promise<string | null> {
    try {
      const binDir = path.join(this.userDataPath, "bin");
      mkdirSync(binDir, { recursive: true });
      const targetBin = path.join(binDir, `vowkey-ax-bridge-${BRIDGE_VERSION}`);
      if (existsSync(targetBin)) {
        this.binaryPath = targetBin;
        return targetBin;
      }
      if (!existsSync("/usr/bin/swiftc")) {
        return null;
      }
      const srcPath = path.join(binDir, `vowkey-ax-bridge-${BRIDGE_VERSION}.swift`);
      const tmpBin = `${targetBin}.tmp-${process.pid}`;
      await fs.writeFile(srcPath, MACOS_AX_BRIDGE_SWIFT, "utf8");
      await run("/usr/bin/swiftc", ["-O", srcPath, "-o", tmpBin], { timeout: 25_000 });
      await fs.rename(tmpBin, targetBin);
      await fs.unlink(srcPath).catch((): void => undefined);
      this.binaryPath = targetBin;
      return targetBin;
    } catch {
      return null;
    } finally {
      this.buildPromise = null;
    }
  }

  async inspect(): Promise<AxInspectResult | null> {
    const bin = await this.ensureBinary();
    if (!bin) {
      return null;
    }
    try {
      const { stdout } = await run(bin, ["inspect"], { timeout: 850 });
      const trimmed = stdout.trim();
      if (!trimmed || trimmed === "{}") {
        return null;
      }
      return JSON.parse(trimmed) as AxInspectResult;
    } catch {
      return null;
    }
  }

  async pasteConcealed(segments: ConcealedSegment[], totp?: string): Promise<boolean> {
    const bin = await this.ensureBinary();
    if (!bin) {
      return false;
    }
    return new Promise<boolean>((resolve) => {
      const child = spawn(bin, ["paste"], { stdio: ["pipe", "ignore", "ignore"] });
      const timer = setTimeout(() => {
        child.kill();
        resolve(false);
      }, 4_000);
      child.on("error", () => {
        clearTimeout(timer);
        resolve(false);
      });
      child.on("close", (code) => {
        clearTimeout(timer);
        resolve(code === 0);
      });
      child.stdin.end(JSON.stringify({ segments, totp: totp || undefined }));
    });
  }

  /**
   * Returns `true` when Vowkey's browser extension is already active in the frontmost browser
   * (either connected over Native Messaging or enabled in Chromium's `Preferences` / `Local State`),
   * so the desktop floating field pill never double-renders on top of the extension's inline pill.
   */
  isBrowserExtensionActive(
    bundleId: string | undefined,
    nativeMessagingMain?: NativeMessagingMain,
  ): boolean {
    if (!bundleId) {
      return false;
    }

    const isBrowserBundle =
      bundleId === "com.google.Chrome" ||
      bundleId === "com.google.Chrome.canary" ||
      bundleId === "com.brave.Browser" ||
      bundleId === "com.microsoft.edgemac" ||
      bundleId === "company.thebrowser.Browser" ||
      bundleId === "com.vivaldi.Vivaldi" ||
      bundleId === "org.chromium.Chromium" ||
      bundleId === "org.mozilla.firefox" ||
      bundleId === "com.apple.Safari";

    if (!isBrowserBundle) {
      return false;
    }

    // 1. Live Native Messaging connection check.
    const clients = (
      nativeMessagingMain as unknown as {
        clients?: Map<number, DesktopIpcPeerClientType>;
      }
    )?.clients;
    if (clients && clients.size > 0) {
      for (const clientType of clients.values()) {
        if (
          clientType === DesktopIpcPeerClientType.Chrome ||
          clientType === DesktopIpcPeerClientType.Firefox ||
          clientType === DesktopIpcPeerClientType.Unknown
        ) {
          return true;
        }
      }
    }

    // 2. Chromium profile Preferences / Local State check (cached 10s).
    const now = Date.now();
    const cached = this.extensionCache.get(bundleId);
    if (cached && cached.expiresAt > now) {
      return cached.active;
    }

    const active = this.checkChromiumExtensionOnDisk(bundleId);
    this.extensionCache.set(bundleId, { active, expiresAt: now + 10_000 });
    return active;
  }

  private checkChromiumExtensionOnDisk(bundleId: string): boolean {
    const appSupport = path.join(os.homedir(), "Library", "Application Support");
    const userDataDirMap: Record<string, string> = {
      "com.google.Chrome": path.join(appSupport, "Google", "Chrome"),
      "com.google.Chrome.canary": path.join(appSupport, "Google", "Chrome Canary"),
      "com.brave.Browser": path.join(appSupport, "BraveSoftware", "Brave-Browser"),
      "com.microsoft.edgemac": path.join(appSupport, "Microsoft Edge"),
      "company.thebrowser.Browser": path.join(appSupport, "Arc", "User Data"),
      "com.vivaldi.Vivaldi": path.join(appSupport, "Vivaldi"),
      "org.chromium.Chromium": path.join(appSupport, "Chromium"),
    };
    const userDataDir = userDataDirMap[bundleId];
    if (!userDataDir || !existsSync(userDataDir)) {
      return false;
    }

    const profiles = ["Default"];
    try {
      const localStatePath = path.join(userDataDir, "Local State");
      if (existsSync(localStatePath)) {
        const localState = JSON.parse(readFileSync(localStatePath, "utf8")) as {
          profile?: { last_used?: string };
        };
        const lastUsed = localState.profile?.last_used;
        if (lastUsed && !profiles.includes(lastUsed)) {
          profiles.unshift(lastUsed);
        }
      }
    } catch {
      // Fall back to Default profile.
    }

    const allowedIds = new Set<string>();
    try {
      const nmhPath = path.join(userDataDir, "NativeMessagingHosts", "com.vowkey.app.json");
      if (existsSync(nmhPath)) {
        const nmh = JSON.parse(readFileSync(nmhPath, "utf8")) as { allowed_origins?: string[] };
        for (const origin of nmh.allowed_origins ?? []) {
          const match = /^chrome-extension:\/\/([a-p]{32})\/?/i.exec(origin);
          if (match?.[1]) {
            allowedIds.add(match[1].toLowerCase());
          }
        }
      }
    } catch {
      // Ignore unreadable NMH manifest.
    }

    for (const profile of profiles) {
      for (const fileName of ["Preferences", "Secure Preferences"]) {
        const prefPath = path.join(userDataDir, profile, fileName);
        if (!existsSync(prefPath)) {
          continue;
        }
        try {
          const parsed = JSON.parse(readFileSync(prefPath, "utf8")) as {
            extensions?: {
              settings?: Record<
                string,
                {
                  state?: number;
                  disable_reasons?: number;
                  path?: string;
                  manifest?: { name?: string };
                }
              >;
            };
          };
          const settings = parsed.extensions?.settings ?? {};
          for (const [extId, entry] of Object.entries(settings)) {
            if (entry?.state !== 1 || (entry.disable_reasons ?? 0) !== 0) {
              continue;
            }
            const name = (entry.manifest?.name ?? "").toLowerCase();
            const extPath = (entry.path ?? "").toLowerCase();
            if (
              allowedIds.has(extId.toLowerCase()) ||
              name.includes("vowkey") ||
              extPath.includes("vowkey")
            ) {
              return true;
            }
          }
        } catch {
          // Ignore malformed profile preferences file.
        }
      }
    }

    return false;
  }
}
